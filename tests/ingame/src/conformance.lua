-- Secret values cannot be formatted, concatenated into results or joined:
-- they are written as `<secret type>`.
local isSecret = issecretvalue or function()
    return false
end

-- A value as text; nested tables only by their type.
local function show(v, depth)
    local t = type(v)
    if isSecret(v) then
        return "<secret " .. t .. ">"
    elseif t == "string" then
        return string.format("%q", v)
    elseif t == "number" or t == "boolean" or t == "nil" then
        return tostring(v)
    elseif t == "table" and depth == 0 then
        local items = {}
        for k, x in pairs(v) do
            items[#items + 1] = show(k, 1) .. "=" .. show(x, 1)
        end
        table.sort(items)
        return "{" .. table.concat(items, ",") .. "}"
    end
    return t
end

local function safe(v)
    local ok, text = pcall(show, v, 0)
    if ok then
        return text
    end
    return "<" .. type(v) .. ">"
end

local function describe(ok, ...)
    local n = select("#", ...)
    local parts = {}
    for i = 1, n do
        parts[i] = safe((select(i, ...)))
    end
    if ok then
        return n .. ": " .. table.concat(parts, ", ")
    end
    return "error: " .. table.concat(parts, ", ")
end

-- Each case's result, by its source. Errors that reach the error handler
-- (securecall, hooks) are recorded with the case instead of shown.
local function run()
    local results = {}
    local handled = {}
    local original = geterrorhandler()
    seterrorhandler(function(err)
        handled[#handled + 1] = isSecret(err) and "<secret>" or tostring(err)
    end)
    local ok, err = pcall(function()
        for _, source in ipairs(cases) do
            local f, syntax = loadstring(source, "=case")
            if f then
                handled = {}
                local result = describe(pcall(f))
                if #handled > 0 then
                    result = result .. " | handler: " .. table.concat(handled, "; ")
                end
                results[source] = result
            else
                results[source] = "syntax: " .. syntax
            end
        end
    end)
    seterrorhandler(original)
    if not ok then
        error(err, 0)
    end
    return results
end

-- Whether each function of the Lua environment is native ("C") or Lua code:
-- `coroutine.create` takes only Lua functions.
local LIBRARIES = { "string", "table", "math", "coroutine", "bit" }

local function kinds()
    local function kind(f)
        return pcall(coroutine.create, f) and "Lua" or "C"
    end
    local result = {}
    for name, value in pairs(_G) do
        if type(name) == "string" and type(value) == "function" and name:match("^[a-z_][a-z0-9_]*$") then
            result[name] = kind(value)
        end
    end
    for _, lib in ipairs(LIBRARIES) do
        if type(_G[lib]) == "table" then
            for name, value in pairs(_G[lib]) do
                if type(value) == "function" then
                    result[lib .. "." .. tostring(name)] = kind(value)
                end
            end
        end
    end
    return result
end

ns.__wowlua.define("conformance", { run = run, kinds = kinds, count = #cases })
