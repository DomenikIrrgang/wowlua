//! The Lua IR: a small tree that can only represent Lua 5.1 (spec compiler
//! §13.4). Every node carries the source position it came from, which drives
//! line preservation, comment placement and source maps.

/// A source position: 1-based Lua line and 0-based byte column. `line == 0`
/// means "generated, no position".
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Pos {
    pub line: u32,
    pub col: u32,
}

impl Pos {
    pub const NONE: Pos = Pos { line: 0, col: 0 };

    pub fn new(line: u32, col: u32) -> Self {
        Pos { line, col }
    }

    pub fn is_some(self) -> bool {
        self.line > 0
    }
}

#[derive(Clone, Debug, Default)]
pub struct Chunk {
    pub block: Block,
    /// Comments of the source, in order, for comment-preserving emission.
    pub comments: Vec<Comment>,
}

#[derive(Clone, Debug)]
pub struct Comment {
    pub pos: Pos,
    pub text: Vec<u8>,
    /// `--[[ … ]]` (may span lines) rather than `-- …`.
    pub block: bool,
    /// Kept by every minification level (spec codegen §14.8.6).
    pub license: bool,
}

#[derive(Clone, Debug, Default)]
pub struct Block {
    pub stmts: Vec<Stmt>,
    /// Position of the token closing the block (`end`, `else`, `until`, …).
    pub end: Pos,
}

#[derive(Clone, Debug)]
pub struct Stmt {
    pub pos: Pos,
    pub kind: StmtKind,
}

// Built once per lowering and walked in place; boxing would only add
// indirection.
#[allow(clippy::large_enum_variant)]
#[derive(Clone, Debug)]
pub enum StmtKind {
    Local {
        names: Vec<Ident>,
        values: Vec<Expr>,
    },
    Assign {
        targets: Vec<Expr>,
        values: Vec<Expr>,
    },
    Call(Expr),
    Do(Block),
    While {
        cond: Expr,
        /// Position of `do`.
        do_pos: Pos,
        body: Block,
    },
    Repeat {
        body: Block,
        cond: Expr,
    },
    /// `if c1 then b1 elseif c2 then b2 … else e end`. Each clause's block
    /// ends at the keyword after it.
    If {
        clauses: Vec<IfClause>,
        else_block: Option<Block>,
    },
    NumericFor {
        var: Ident,
        start: Expr,
        limit: Expr,
        step: Option<Expr>,
        do_pos: Pos,
        body: Block,
    },
    GenericFor {
        vars: Vec<Ident>,
        exprs: Vec<Expr>,
        do_pos: Pos,
        body: Block,
    },
    Function {
        path: Vec<Ident>,
        method: Option<Ident>,
        func: Func,
    },
    LocalFunction {
        name: Ident,
        func: Func,
    },
    Return(Vec<Expr>),
    Break,
}

/// `cond then body` of an `if` or `elseif`.
#[derive(Clone, Debug)]
pub struct IfClause {
    pub cond: Expr,
    /// Position of `then`.
    pub then_pos: Pos,
    pub body: Block,
}

#[derive(Clone, Debug)]
pub struct Ident {
    pub name: String,
    /// Generated by the compiler (`__wl…`); hygiene may rename it.
    pub generated: bool,
    pub pos: Pos,
}

impl Ident {
    pub fn new(name: impl Into<String>, pos: Pos) -> Self {
        Ident {
            name: name.into(),
            generated: false,
            pos,
        }
    }
}

#[derive(Clone, Debug)]
pub struct Func {
    /// Position of the parameter list's `(`.
    pub pos: Pos,
    pub params: Vec<Ident>,
    pub vararg: bool,
    /// Ends at the function's `end`.
    pub body: Block,
}

#[derive(Clone, Debug)]
pub struct Expr {
    pub pos: Pos,
    pub kind: ExprKind,
    /// In a list: position of the `,` (or `;`) after this element.
    pub sep: Pos,
}

impl Expr {
    pub fn new(kind: ExprKind, pos: Pos) -> Self {
        Expr {
            pos,
            kind,
            sep: Pos::NONE,
        }
    }
}

#[derive(Clone, Debug)]
pub enum ExprKind {
    Nil,
    True,
    False,
    /// A Lua 5.1 numeral, as it is emitted.
    Number(String),
    /// A string literal as it is emitted, including quotes or brackets.
    String(Vec<u8>),
    Vararg,
    Function(Box<Func>),
    Table {
        fields: Vec<Field>,
        close: Pos,
    },
    Name(Ident),
    Index {
        obj: Box<Expr>,
        key: Box<Expr>,
    },
    Field {
        obj: Box<Expr>,
        name: Ident,
    },
    Call {
        callee: Box<Expr>,
        args: Args,
    },
    Method {
        obj: Box<Expr>,
        name: Ident,
        args: Args,
    },
    /// Parentheses are kept: they truncate multiple values.
    Paren {
        inner: Box<Expr>,
        close: Pos,
    },
    Binary {
        op: BinOp,
        /// Position of the operator (Lua emits code when it reads it).
        op_pos: Pos,
        lhs: Box<Expr>,
        rhs: Box<Expr>,
    },
    Unary {
        op: UnOp,
        operand: Box<Expr>,
    },
}

#[derive(Clone, Debug)]
pub enum Args {
    Parens {
        args: Vec<Expr>,
        close: Pos,
    },
    /// `f{…}`: a table constructor expression.
    Table(Box<Expr>),
    /// `f"…"`: a string expression.
    String(Box<Expr>),
}

#[derive(Clone, Debug)]
pub enum Field {
    /// `[key] = value`; `open` is the position of `[`.
    Keyed {
        open: Pos,
        key: Expr,
        value: Expr,
    },
    Named {
        name: Ident,
        value: Expr,
    },
    Positional(Expr),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BinOp {
    Add,
    Sub,
    Mul,
    Div,
    Mod,
    Pow,
    Concat,
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
    And,
    Or,
}

impl BinOp {
    /// Lua 5.1 left and right priorities (lparser.c).
    pub fn priority(self) -> (u8, u8) {
        use BinOp::*;
        match self {
            Or => (1, 1),
            And => (2, 2),
            Eq | Ne | Lt | Le | Gt | Ge => (3, 3),
            Concat => (5, 4),
            Add | Sub => (6, 6),
            Mul | Div | Mod => (7, 7),
            Pow => (10, 9),
        }
    }

    pub fn as_str(self) -> &'static str {
        use BinOp::*;
        match self {
            Add => "+",
            Sub => "-",
            Mul => "*",
            Div => "/",
            Mod => "%",
            Pow => "^",
            Concat => "..",
            Eq => "==",
            Ne => "~=",
            Lt => "<",
            Le => "<=",
            Gt => ">",
            Ge => ">=",
            And => "and",
            Or => "or",
        }
    }
}

/// Lua 5.1's unary priority.
pub const UNARY_PRIORITY: u8 = 8;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum UnOp {
    Neg,
    Not,
    Len,
}

impl UnOp {
    pub fn as_str(self) -> &'static str {
        match self {
            UnOp::Neg => "-",
            UnOp::Not => "not",
            UnOp::Len => "#",
        }
    }
}
