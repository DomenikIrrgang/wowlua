//! The Lua IR: a small tree that can only represent Lua 5.1 (spec compiler
//! §13.4). Every node carries the source position it came from, which drives
//! line preservation, comment placement and source maps.

/// A source position: 1-based Lua line and 0-based byte column. `line == 0`
/// means "generated, no position".
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Pos {
    pub line: u32,
    pub col: u32,
}

impl Pos {
    pub const NONE: Pos = Pos { line: 0, col: 0 };

    pub fn new(line: u32, col: u32) -> Self {
        Pos { line, col }
    }

    pub fn is_some(self) -> bool {
        self.line > 0
    }
}

#[derive(Clone, Debug, Default)]
pub struct Chunk {
    pub block: Block,
    /// Comments of the source, in order, for comment-preserving emission.
    pub comments: Vec<Comment>,
}

#[derive(Clone, Debug)]
pub struct Comment {
    pub pos: Pos,
    pub text: Vec<u8>,
    /// `--[[ … ]]` (may span lines) rather than `-- …`.
    pub block: bool,
    /// Kept by every minification level (spec codegen §14.8.6).
    pub license: bool,
}

#[derive(Clone, Debug, Default)]
pub struct Block {
    pub stmts: Vec<Stmt>,
    /// Position of the token closing the block (`end`, `else`, `until`, …).
    pub end: Pos,
}

#[derive(Clone, Debug)]
pub struct Stmt {
    pub pos: Pos,
    pub kind: StmtKind,
}

// Built once per lowering and walked in place; boxing would only add
// indirection.
#[allow(clippy::large_enum_variant)]
#[derive(Clone, Debug)]
pub enum StmtKind {
    Local {
        names: Vec<Ident>,
        values: Vec<Expr>,
    },
    Assign {
        targets: Vec<Expr>,
        values: Vec<Expr>,
    },
    Call(Expr),
    Do(Block),
    While {
        cond: Expr,
        /// Position of `do`.
        do_pos: Pos,
        body: Block,
    },
    Repeat {
        body: Block,
        cond: Expr,
    },
    /// `if c1 then b1 elseif c2 then b2 … else e end`. Each clause's block
    /// ends at the keyword after it.
    If {
        clauses: Vec<IfClause>,
        else_block: Option<Block>,
    },
    NumericFor {
        var: Ident,
        start: Box<Expr>,
        limit: Box<Expr>,
        step: Option<Box<Expr>>,
        do_pos: Pos,
        body: Block,
    },
    GenericFor {
        vars: Vec<Ident>,
        exprs: Vec<Expr>,
        do_pos: Pos,
        body: Block,
    },
    Function {
        path: Vec<Ident>,
        method: Option<Ident>,
        func: Func,
    },
    LocalFunction {
        name: Ident,
        func: Func,
    },
    Return(Vec<Expr>),
    Break,
}

/// `cond then body` of an `if` or `elseif`.
#[derive(Clone, Debug)]
pub struct IfClause {
    pub cond: Expr,
    /// Position of `then`.
    pub then_pos: Pos,
    pub body: Block,
}

/// A name and where it is. Whether the compiler generated it (`__wl…`;
/// hygiene may rename it) is kept in the name's spare room
/// ([`Ident::generated`]): assign a new name with [`Ident::rename`].
#[derive(Clone)]
pub struct Ident {
    pub name: crate::lit::Name,
    pub pos: Pos,
}

impl Ident {
    /// A name of the source's (not generated), whatever `name` was.
    pub fn new(name: impl Into<crate::lit::Name>, pos: Pos) -> Self {
        let mut id = Ident {
            name: name.into(),
            pos,
        };
        id.set_generated(false);
        id
    }

    /// A name the compiler generated.
    pub fn new_generated(name: impl Into<crate::lit::Name>, pos: Pos) -> Self {
        let mut id = Ident::new(name, pos);
        id.set_generated(true);
        id
    }

    /// Generated by the compiler (`__wl…`); hygiene may rename it.
    pub fn generated(&self) -> bool {
        self.name.flag()
    }

    pub fn set_generated(&mut self, generated: bool) {
        self.name.set_flag(generated);
    }

    /// Gives the identifier the name `name`, generated or not as before,
    /// with its facts.
    pub fn rename(&mut self, name: impl Into<crate::lit::Name>) {
        let generated = self.generated();
        let facts = self.facts();
        self.name = name.into();
        self.set_generated(generated);
        self.set_facts(facts);
    }

    /// What the type checker proved where the identifier is: of the object
    /// when it names a field ([`Facts::PLAIN`]), of the arguments when it
    /// names the function a call calls ([`Facts::ARG_ARRAY`],
    /// [`Facts::ARG_PLAIN`]).
    pub fn facts(&self) -> Facts {
        Facts(self.name.facts())
    }

    pub fn set_facts(&mut self, facts: Facts) {
        self.name.set_facts(facts.0);
    }
}

/// What the type checker proved of an IR node, in strict mode (spec
/// optimization §15.2.3): the optimizations that need types read these and
/// nothing else, so code without them (basic mode, plain Lua, `any`) stays
/// as it is. Kept in room the nodes have anyway.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct Facts(pub u8);

impl Facts {
    pub const NONE: Facts = Facts(0);
    /// A field's name, an index: the object is a table, never `nil`, whose
    /// reads and writes run no code (no `__index` or `__newindex`
    /// function): reading it cannot fail or change anything.
    pub const PLAIN: Facts = Facts(1);
    /// A called function's name (`ipairs`): its argument is a plain array.
    pub const ARG_ARRAY: Facts = Facts(2);
    /// A called function's name (`insert` of `table.insert`, `tinsert`):
    /// its first argument is a plain table.
    pub const ARG_PLAIN: Facts = Facts(4);
    /// An operator: its operands are of types it takes without a
    /// metamethod (numbers for arithmetic, strings or numbers for `..`, …),
    /// so it runs no code.
    pub const NO_META: Facts = Facts(8);

    pub fn has(self, f: Facts) -> bool {
        self.0 & f.0 == f.0 && f.0 != 0
    }

    pub fn with(self, f: Facts) -> Facts {
        Facts(self.0 | f.0)
    }
}

impl std::fmt::Debug for Ident {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Ident")
            .field("name", &self.name)
            .field("generated", &self.generated())
            .field("pos", &self.pos)
            .finish()
    }
}

#[derive(Clone, Debug)]
pub struct Func {
    /// Position of the parameter list's `(`.
    pub pos: Pos,
    pub params: Vec<Ident>,
    pub vararg: bool,
    /// Ends at the function's `end`.
    pub body: Block,
}

#[derive(Clone, Debug)]
pub struct Expr {
    pub pos: Pos,
    pub kind: ExprKind,
    /// In a list: position of the `,` (or `;`) after this element.
    pub sep: Pos,
}

impl Expr {
    pub fn new(kind: ExprKind, pos: Pos) -> Self {
        Expr {
            pos,
            kind,
            sep: Pos::NONE,
        }
    }
}

#[derive(Clone, Debug)]
pub enum ExprKind {
    Nil,
    True,
    False,
    /// A Lua 5.1 numeral, as it is emitted.
    Number(crate::lit::Numeral),
    /// A string literal as it is emitted, including quotes or brackets.
    String(crate::lit::StrLit),
    Vararg,
    Function(Box<Func>),
    Table {
        fields: Vec<Field>,
        close: Pos,
    },
    Name(Ident),
    Index {
        obj: Box<Expr>,
        key: Box<Expr>,
        /// [`Facts::PLAIN`] for the object.
        facts: Facts,
    },
    Field {
        obj: Box<Expr>,
        name: Ident,
    },
    Call {
        callee: Box<Expr>,
        args: Args,
    },
    Method {
        obj: Box<Expr>,
        name: Box<Ident>,
        args: Args,
    },
    /// Parentheses are kept: they truncate multiple values.
    Paren {
        inner: Box<Expr>,
        close: Pos,
    },
    Binary {
        op: BinOp,
        /// [`Facts::NO_META`].
        facts: Facts,
        /// Position of the operator (Lua emits code when it reads it).
        op_pos: Pos,
        lhs: Box<Expr>,
        rhs: Box<Expr>,
    },
    Unary {
        op: UnOp,
        /// [`Facts::NO_META`].
        facts: Facts,
        operand: Box<Expr>,
    },
}

#[derive(Clone, Debug)]
pub enum Args {
    Parens {
        args: Vec<Expr>,
        close: Pos,
    },
    /// `f{…}`: a table constructor expression.
    Table(Box<Expr>),
    /// `f"…"`: a string expression.
    String(Box<Expr>),
}

#[derive(Clone, Debug)]
pub enum Field {
    /// `[key] = value`; `open` is the position of `[`.
    Keyed {
        open: Pos,
        key: Box<Expr>,
        value: Expr,
    },
    Named {
        name: Ident,
        value: Expr,
    },
    Positional(Expr),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BinOp {
    Add,
    Sub,
    Mul,
    Div,
    Mod,
    Pow,
    Concat,
    Eq,
    Ne,
    Lt,
    Le,
    Gt,
    Ge,
    And,
    Or,
}

impl BinOp {
    /// Lua 5.1 left and right priorities (lparser.c).
    pub fn priority(self) -> (u8, u8) {
        use BinOp::*;
        match self {
            Or => (1, 1),
            And => (2, 2),
            Eq | Ne | Lt | Le | Gt | Ge => (3, 3),
            Concat => (5, 4),
            Add | Sub => (6, 6),
            Mul | Div | Mod => (7, 7),
            Pow => (10, 9),
        }
    }

    pub fn as_str(self) -> &'static str {
        use BinOp::*;
        match self {
            Add => "+",
            Sub => "-",
            Mul => "*",
            Div => "/",
            Mod => "%",
            Pow => "^",
            Concat => "..",
            Eq => "==",
            Ne => "~=",
            Lt => "<",
            Le => "<=",
            Gt => ">",
            Ge => ">=",
            And => "and",
            Or => "or",
        }
    }
}

/// Lua 5.1's unary priority.
pub const UNARY_PRIORITY: u8 = 8;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum UnOp {
    Neg,
    Not,
    Len,
}

impl UnOp {
    pub fn as_str(self) -> &'static str {
        match self {
            UnOp::Neg => "-",
            UnOp::Not => "not",
            UnOp::Len => "#",
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Rarely used parts stay boxed (#11, phase C): every expression,
    /// table field and statement of a file's IR is this size.
    #[test]
    fn ir_nodes_stay_small() {
        assert!(std::mem::size_of::<Expr>() <= 72);
        assert!(std::mem::size_of::<Field>() <= 112);
        assert!(std::mem::size_of::<Stmt>() <= 144);
    }
}
