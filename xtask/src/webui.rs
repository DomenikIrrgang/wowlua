//! The Blizzard UI files the playground fetches (spec M14 S3, decision
//! T396): per flavor, the files loading its UI, logging in and its first
//! three seconds read, and the rest of its addons' code, written to `crates/wowlua-web/ui/<flavor>.txt`.
//! `cargo xtask web-ui` writes them from the fetched UI code; `check`
//! makes sure each names the commit the flavor's declarations name.

use anyhow::{Context, Result, anyhow, bail};
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex};
use wowlua_engine::host::{Host, Kind};

/// The flavors the playground runs.
pub const FLAVORS: &[&str] = &["camelot"];

pub fn path(root: &Path, flavor: &str) -> PathBuf {
    root.join("crates/wowlua-web/ui")
        .join(format!("{flavor}.txt"))
}

/// The disk, with every file read recorded.
struct Recording(Mutex<BTreeSet<PathBuf>>);

impl Host for Recording {
    fn read(&self, p: &Path) -> std::io::Result<Vec<u8>> {
        let bytes = std::fs::read(p)?;
        self.0.lock().expect("a lock").insert(p.to_path_buf());
        Ok(bytes)
    }
    fn kind(&self, p: &Path) -> Option<Kind> {
        let m = std::fs::metadata(p).ok()?;
        Some(if m.is_dir() { Kind::Dir } else { Kind::File })
    }
    fn read_dir(&self, p: &Path) -> std::io::Result<Vec<PathBuf>> {
        Ok(std::fs::read_dir(p)?.flatten().map(|e| e.path()).collect())
    }
    fn write(&self, _: &Path, _: &[u8]) -> std::io::Result<()> {
        Err(std::io::Error::other("read only"))
    }
    fn create_dir_all(&self, _: &Path) -> std::io::Result<()> {
        Err(std::io::Error::other("read only"))
    }
    fn remove_file(&self, _: &Path) -> std::io::Result<()> {
        Err(std::io::Error::other("read only"))
    }
    fn remove_dir_all(&self, _: &Path) -> std::io::Result<()> {
        Err(std::io::Error::other("read only"))
    }
    fn rename(&self, _: &Path, _: &Path) -> std::io::Result<()> {
        Err(std::io::Error::other("read only"))
    }
    fn canonicalize(&self, p: &Path) -> std::io::Result<PathBuf> {
        std::fs::canonicalize(p)
    }
}

/// The list for `flavor`, from its UI code (fetched when not cached).
pub fn generate(flavor: &str) -> Result<String> {
    let (commit, strings) =
        wowlua_test::ui_commits(flavor).ok_or_else(|| anyhow!("no UI commit for {flavor}"))?;
    let ui =
        wowlua_test::ui_source(flavor, &|s| eprintln!("fetching {s}")).map_err(|e| anyhow!(e))?;
    let base = ui
        .interface
        .parent()
        .context("the UI's folder")?
        .to_path_buf();
    let recording = Arc::new(Recording(Mutex::new(BTreeSet::new())));
    wowlua_engine::host::install(Some(recording.clone()));
    let mut vm = wowlua_vm::Vm::wow();
    wowlua_engine::install(&mut vm, flavor).map_err(|e| anyhow!(e))?;
    let report = wowlua_engine::ui::load(&mut vm, &ui.interface, ui.strings.as_deref());
    if !report.errors.is_empty() {
        wowlua_engine::host::install(None);
        bail!(
            "{flavor}'s UI raised {} errors loading",
            report.errors.len()
        );
    }
    // Logging in and the first seconds load addons on demand too
    // (`Blizzard_PlayerChoice`): their files are needed at once as well.
    wowlua_engine::login::login(&mut vm, "Playground", false, false);
    wowlua_engine::clock::advance_frames(&mut vm, 180, 1000.0 / 60.0);
    wowlua_engine::host::install(None);
    let rel = |p: &Path| -> Option<String> {
        Some(
            p.strip_prefix(&base)
                .ok()?
                .to_string_lossy()
                .replace('\\', "/"),
        )
    };
    let read = recording.0.lock().expect("a lock");
    let startup: BTreeSet<String> = read.iter().filter_map(|p| rel(p)).collect();
    let later: BTreeSet<String> = walkdir::WalkDir::new(ui.interface.join("AddOns"))
        .into_iter()
        .flatten()
        .filter(|e| e.file_type().is_file())
        .filter(|e| {
            let n = e.file_name().to_string_lossy().to_ascii_lowercase();
            n.ends_with(".lua") || n.ends_with(".xml") || n.ends_with(".toc")
        })
        .filter_map(|e| rel(e.path()))
        .filter(|p| !startup.contains(p))
        .collect();
    let mut out = format!(
        "# Blizzard's UI files the playground fetches for {flavor}: what loading it reads,\n\
         # then the rest of its addons' code. Generated by `cargo xtask web-ui`; do not edit.\n\
         commit {commit}\n"
    );
    if let Some(s) = strings {
        out.push_str(&format!("strings {s}\n"));
    }
    out.push_str("startup\n");
    for p in &startup {
        out.push_str(p);
        out.push('\n');
    }
    out.push_str("later\n");
    for p in &later {
        out.push_str(p);
        out.push('\n');
    }
    Ok(out)
}

/// Each list names the commit its flavor's declarations name.
pub fn check(root: &Path) -> Result<()> {
    for flavor in FLAVORS {
        let file = path(root, flavor);
        let text = std::fs::read_to_string(&file)
            .with_context(|| format!("{}: run `cargo xtask web-ui`", file.display()))?;
        let (commit, _) =
            wowlua_test::ui_commits(flavor).ok_or_else(|| anyhow!("no UI commit for {flavor}"))?;
        if !text.lines().any(|l| l == format!("commit {commit}")) {
            bail!(
                "{} is of another commit than the {flavor} declarations: run `cargo xtask web-ui`",
                file.display()
            );
        }
    }
    Ok(())
}
