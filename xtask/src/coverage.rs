/// `33727` as `33,727`.
fn thousands(n: usize) -> String {
    let digits = n.to_string();
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

/// `part` of `whole` as a percentage, one decimal.
fn percent(part: usize, whole: usize) -> String {
    if whole == 0 {
        return "-".into();
    }
    format!("{:.1}%", part as f64 * 100.0 / whole as f64)
}

/// A Lua fixture's table of strings (`return { ["k"] = "v", ... }`).
fn lua_strings(path: &Path) -> Result<BTreeMap<String, String>> {
    let src = fs::read(path).with_context(|| path.display().to_string())?;
    let mut vm = Vm::new();
    let f = vm.load(&src, "=fixture").map_err(anyhow::Error::msg)?;
    let r = vm
        .call(f, &[])
        .map_err(|e| anyhow::anyhow!("{}: {:?}", path.display(), e.value))?;
    let Some(Value::Table(t)) = r.first().copied() else {
        bail!("{} returns no table", path.display());
    };
    let text = |vm: &Vm, s| String::from_utf8_lossy(vm.str_bytes(s)).into_owned();
    Ok(vm
        .heap
        .table(t)
        .entries()
        .filter_map(|(k, v)| match (k, v) {
            (Value::Str(k), Value::Str(v)) => Some((text(&vm, k), text(&vm, v))),
            _ => None,
        })
        .collect())
}

/// Counts of each source.
#[derive(Default, Clone, Copy)]
pub(crate) struct Counts {
    pub(crate) model: usize,
    pub(crate) recorded: usize,
    pub(crate) fill_in: usize,
    pub(crate) generated: usize,
}

impl Counts {
    pub(crate) fn add(&mut self, source: Source) {
        match source {
            Source::Model => self.model += 1,
            Source::Recorded => self.recorded += 1,
            Source::FillIn => self.fill_in += 1,
            Source::Generated => self.generated += 1,
        }
    }

    fn merge(&mut self, other: &Counts) {
        self.model += other.model;
        self.recorded += other.recorded;
        self.fill_in += other.fill_in;
        self.generated += other.generated;
    }

    pub(crate) fn total(&self) -> usize {
        self.model + self.recorded + self.fill_in + self.generated
    }

    fn answered(&self) -> usize {
        self.model + self.recorded + self.fill_in
    }

    fn row(&self, label: &str) -> String {
        format!(
            "| {label} | {} | {} | {} | {} | {} |\n",
            thousands(self.total()),
            thousands(self.model),
            thousands(self.recorded),
            thousands(self.fill_in),
            thousands(self.generated)
        )
    }
}

pub(crate) fn counts<'a>(entries: impl Iterator<Item = &'a Entry>) -> Counts {
    let mut c = Counts::default();
    for e in entries {
        c.add(e.source);
    }
    c
}

/// A function's namespace (`C_Timer`), `(globals)` for a global.
fn namespace(name: &str) -> &str {
    name.split_once('.').map_or("(globals)", |(ns, _)| ns)
}

// ------------------------------------------------------------- summary

fn summary(
    out: &mut String,
    root: &Path,
    functions: &[Entry],
    methods: &[Entry],
    v: &Verification,
    unverified: &[Rule],
) -> Result<()> {
    out.push_str("## Summary\n\n");
    // The client builds the recordings come from (`recorded.txt`).
    let recorded = fs::read_to_string(root.join(CLIENT).join("recorded.txt"))?;
    let builds: BTreeSet<&str> = recorded
        .lines()
        .filter(|l| !l.starts_with('#'))
        .filter_map(|l| l.split('\t').nth(2))
        .collect();
    let builds: Vec<String> = builds.iter().map(|b| format!("WoW Forever {b}")).collect();
    let documented = counts(functions.iter().filter(|e| e.group == Group::Documented));
    let client = counts(functions.iter().filter(|e| e.group != Group::EngineOnly));
    let m = counts(methods.iter());
    let scenarios = &v.scenarios;
    let (lines_matched, lines_total) = scenarios
        .iter()
        .fold((0, 0), |(a, b), s| (a + s.matched, b + s.total));
    let exact = scenarios.iter().filter(|s| s.matched == s.total).count();
    writeln!(
        out,
        "Every recording comes from the camelot flavor ({}), the client the engine is \
         built against: its numbers below are measured against what that client \
         answered. The other flavors have their API documentation, the same engine \
         modules and the generated stand-ins, but no recording of their own: what their \
         clients answer differently is unverified.\n",
        builds.join(", ")
    )?;
    writeln!(
        out,
        "- **API functions:** {} of the {} documented camelot functions have behaviour \
         ({}): {} modelled, {} answered from recordings, {} by a documentation-based \
         fill-in. Of all {} C functions the client has, documented or not, {} have \
         behaviour.",
        thousands(documented.answered()),
        thousands(documented.total()),
        percent(documented.answered(), documented.total()),
        thousands(documented.model),
        thousands(documented.recorded),
        thousands(documented.fill_in),
        thousands(client.total()),
        thousands(client.answered()),
    )?;
    writeln!(
        out,
        "- **Widget methods:** {} of the {} documented methods have behaviour ({}).",
        thousands(m.answered()),
        thousands(m.total()),
        percent(m.answered(), m.total()),
    )?;
    writeln!(
        out,
        "- **Full probe:** {} of the client's {} answers given as the client gave them ({}).",
        thousands(v.fullprobe.matched),
        thousands(v.fullprobe.total),
        percent(v.fullprobe.matched, v.fullprobe.total),
    )?;
    writeln!(
        out,
        "- **Scenario replays:** {} of {} recorded lines replayed as the client logged them \
         ({}); {} of {} scenarios line for line.",
        thousands(lines_matched),
        thousands(lines_total),
        percent(lines_matched, lines_total),
        exact,
        scenarios.len(),
    )?;
    writeln!(
        out,
        "- **Unverified rules:** {} comments in the engine mark a rule unverified.\n",
        thousands(unverified.len())
    )?;
    out.push_str(
        "| Flavor | Documented functions | With behaviour | Recorded answers | Widget methods | With behaviour | Recordings |\n\
         |--------|---------------------:|---------------:|-----------------:|---------------:|---------------:|------------|\n",
    );
    for flavor in &wowlua_flavors::table().flavors {
        let id = flavor.id.as_str();
        if wowlua_engine::api::api(id).is_none() {
            continue;
        }
        let (f, m) = if id == FOCUS {
            (functions.to_vec(), methods.to_vec())
        } else {
            (
                wowlua_engine::coverage::functions(id).map_err(anyhow::Error::msg)?,
                wowlua_engine::coverage::methods(id).map_err(anyhow::Error::msg)?,
            )
        };
        let f = counts(f.iter().filter(|e| e.group == Group::Documented));
        let m = counts(m.iter());
        writeln!(
            out,
            "| {id} | {} | {} ({}) | {} | {} | {} ({}) | {} |",
            thousands(f.total()),
            thousands(f.answered()),
            percent(f.answered(), f.total()),
            thousands(f.recorded),
            thousands(m.total()),
            thousands(m.answered()),
            percent(m.answered(), m.total()),
            if id == FOCUS { "all" } else { "none" },
        )?;
    }
    out.push('\n');
    Ok(())
}

// ----------------------------------------------------------- behaviour

fn behaviour(out: &mut String, functions: &[Entry], methods: &[Entry], inventory: &str) {
    out.push_str("## API behaviour\n\n");
    out.push_str(
        "Each function's answer comes from one place, the first of these that has one \
         (as the engine installs them):\n\n\
         - **Model:** an engine module models the system or applies a probed rule (the \
         world's units, auras, bags, quests, the clock...), or the VM's runtime defines \
         the function.\n\
         - **Recorded:** the client's recorded answers (`data/camelot-answers.txt`, the \
         load-time answers, the talent trees), looked up by the call.\n\
         - **Fill-in:** a fill-in module's answer, worked out from Blizzard's \
         documentation and UI code and the function's name (unverified), or the \
         answer the full probe got with nothing there (`blanks`).\n\
         - **Generated:** only the stand-in generated from the documentation: an \
         addon's call fails with \"`<name>` is not mocked\", Blizzard's code gets the \
         documented types' empty values.\n\n\
         camelot, by namespace (the documented functions and the client's undocumented \
         ones together):\n\n",
    );
    let header = "| Namespace | Functions | Model | Recorded | Fill-in | Generated |\n\
                  |-----------|----------:|------:|---------:|--------:|----------:|\n";
    out.push_str(header);
    let mut by_group: BTreeMap<Group, Counts> = BTreeMap::new();
    let mut by_ns: BTreeMap<&str, Counts> = BTreeMap::new();
    for e in functions {
        by_group.entry(e.group).or_default().add(e.source);
        if e.group != Group::EngineOnly {
            by_ns.entry(namespace(&e.name)).or_default().add(e.source);
        }
    }
    let mut all = Counts::default();
    for (ns, c) in &by_ns {
        out.push_str(&c.row(&format!("`{ns}`")));
        all.merge(c);
    }
    out.push_str(&all.row("**All**"));
    out.push('\n');
    out.push_str("By where the function is listed:\n\n");
    out.push_str(
        &header
            .replace("Namespace", "List")
            .replacen("|-----------|", "|------|", 1),
    );
    for (group, c) in &by_group {
        let label = match group {
            Group::Documented => "Blizzard's API documentation",
            Group::Undocumented => "the client's other C functions (`/stdtest inventory`)",
            Group::EngineOnly => "the engine's own, in neither list",
        };
        out.push_str(&c.row(label));
    }
    out.push('\n');
    // The client's Lua functions: Blizzard's UI code defines them (its
    // deprecation files' `HasAction`), the engine's natives stand in until
    // it loads.
    let lua: BTreeSet<&str> = inventory
        .lines()
        .filter_map(|l| l.strip_suffix("\tLua"))
        .collect();
    let (blizzard, engine_only): (Vec<&Entry>, Vec<&Entry>) = functions
        .iter()
        .filter(|e| e.group == Group::EngineOnly)
        .partition(|e| lua.contains(e.name.as_str()));
    let quoted = |list: &[&Entry]| -> String {
        list.iter()
            .map(|e| format!("`{}`", e.name))
            .collect::<Vec<_>>()
            .join(", ")
    };
    if !blizzard.is_empty() {
        writeln!(
            out,
            "Of the engine's own, Blizzard's UI code defines these in the client (Lua \
             functions in the client's inventory, its deprecation files' wrappers of the \
             `C_` functions); the engine's natives stand in for them until that code \
             loads: {}.\n",
            quoted(&blizzard)
        )
        .unwrap();
    }
    if !engine_only.is_empty() {
        writeln!(
            out,
            "The engine's own functions are defined in camelot's environment though the \
             client's inventory lacks them, so an addon's call of one works in `wowlua \
             test` and fails in the game (behaviour the engine shares between flavors, \
             or protected functions it adds): {}.\n",
            quoted(&engine_only)
        )
        .unwrap();
    }
    // The modules that answer.
    let mut by_module: BTreeMap<(&str, Source), usize> = BTreeMap::new();
    for e in functions.iter().chain(methods) {
        if e.source != Source::Generated {
            *by_module.entry((e.module, e.source)).or_default() += 1;
        }
    }
    let mut modules: Vec<((&str, Source), usize)> = by_module.into_iter().collect();
    modules.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(&b.0)));
    out.push_str("The modules that answer, by how many functions and methods:\n\n");
    out.push_str(
        "| Module | Kind | Functions and methods |\n|--------|------|----------------------:|\n",
    );
    for ((module, source), n) in modules {
        let kind = match source {
            Source::Model => "model",
            Source::Recorded => "recorded",
            Source::FillIn => "fill-in",
            Source::Generated => "generated",
        };
        writeln!(out, "| `{module}` | {kind} | {} |", thousands(n)).unwrap();
    }
    out.push('\n');
    out.push_str(
        "Widget methods by the documentation's class (a setter without behaviour stores \
         its arguments for the getter, which counts as a model; a getter answers a \
         fresh widget's recorded value where `/stdtest engine` recorded one):\n\n",
    );
    out.push_str(
        &header
            .replace("Namespace", "Class")
            .replace("Functions", "Methods")
            .replacen("|-----------|", "|-------|", 1),
    );
    let mut by_class: BTreeMap<&str, Counts> = BTreeMap::new();
    for e in methods {
        let class = e.name.split_once(':').map_or("", |(c, _)| c);
        by_class.entry(class).or_default().add(e.source);
    }
    for (class, c) in &by_class {
        out.push_str(&c.row(&format!("`{class}`")));
    }
    out.push_str(&counts(methods.iter()).row("**All**"));
    out.push('\n');
}

// -------------------------------------------------------- verification

/// A replay or probe: matched of total.
struct Measure {
    matched: usize,
    total: usize,
}

struct Scenario {
    name: String,
    matched: usize,
    total: usize,
}

struct Verification {
    fullprobe: Measure,
    /// The full probe's answers and misses by namespace.
    fullprobe_ns: BTreeMap<String, (usize, usize)>,
    methodprobe: Measure,
    methodprobe_seed: bool,
    answers: Measure,
    checks: usize,
    maps: Measure,
    damage_meter: Measure,
    scenarios: Vec<Scenario>,
    /// Recordings no replay test plays yet.
    unplayed: Vec<String>,
}

/// A misses file (`write_misses` in engine_probe.rs): matched, total and
/// the misses by function.
fn misses(root: &Path, file: &str) -> Result<(usize, usize, BTreeMap<String, usize>)> {
    let text = fs::read_to_string(root.join(file)).with_context(|| file.to_string())?;
    let (mut matched, mut total, mut by) = (None, None, BTreeMap::new());
    for line in text
        .lines()
        .filter(|l| !l.starts_with('#') && !l.is_empty())
    {
        let Some((k, n)) = line.rsplit_once('\t') else {
            bail!("{file}: {line:?}");
        };
        let n: usize = n.parse().with_context(|| format!("{file}: {line:?}"))?;
        match k {
            "matched" => matched = Some(n),
            "total" => total = Some(n),
            _ => {
                by.insert(k.to_string(), n);
            }
        }
    }
    let (Some(matched), Some(total)) = (matched, total) else {
        bail!("{file}: no matched or total line");
    };
    Ok((matched, total, by))
}

/// The full probe's answers the engine gives as the client gave them, and
/// all of them (the report's "Full probe" line).
pub(crate) fn full_probe(root: &Path) -> Result<(usize, usize)> {
    let v = Verification::read(root)?;
    Ok((v.fullprobe.matched, v.fullprobe.total))
}

impl Verification {
    fn read(root: &Path) -> Result<Verification> {
        let tests = fs::read_to_string(root.join(PROBE_TESTS))?;
        let ratchets: BTreeMap<String, usize> = Regex::new(r"const ([A-Z0-9_]+): usize = (\d+);")?
            .captures_iter(&tests)
            .map(|c| (c[1].to_string(), c[2].parse().unwrap_or(0)))
            .collect();
        let ratchet = |name: &str| -> Result<usize> {
            ratchets
                .get(name)
                .copied()
                .with_context(|| format!("no `{name}` in {PROBE_TESTS}"))
        };
        let client = root.join(CLIENT);
        let stale = |what: &str, file: &str| -> anyhow::Error {
            anyhow::anyhow!(
                "{file} is out of date ({what}): run `WOWLUA_COVERAGE_WRITE=1 cargo test -p \
                 wowlua-cli --test engine_probe probe_as_the_client` with Blizzard's UI code \
                 (`cargo xtask types fetch`), with the test's ratchet at what it matches"
            )
        };
        // The full probe: the fixture's answers (as the test counts them)
        // by function, and the test's misses.
        let fixture = lua_strings(&client.join("forever-camelot-fullprobe.lua"))?;
        let name_of = Regex::new(r"^(?:set )?([A-Za-z0-9_.:]+)")?;
        let mut asked: BTreeMap<String, usize> = BTreeMap::new();
        for (k, v) in &fixture {
            if v == "crashed" || v.starts_with("unresolved: ") || v.starts_with("skipped: ") {
                continue;
            }
            // As the test names it: `set X` for a setting's read-back.
            let name = name_of
                .captures(k)
                .and_then(|c| c.get(1))
                .map_or(k.as_str(), |m| m.as_str());
            *asked.entry(name.to_string()).or_default() += 1;
        }
        let total: usize = asked.values().sum();
        let matched = ratchet("FULLPROBE_MATCHED")?;
        let (m, t, missed) = misses(root, FULLPROBE_MISSES)?;
        let sum: usize = missed.values().sum();
        if m != matched || t != total || t - sum != m {
            return Err(stale(
                &format!(
                    "{m} matched of {t} with {sum} missed; the test's ratchet {matched}, the \
                     fixture's {total} answers"
                ),
                FULLPROBE_MISSES,
            ));
        }
        let mut fullprobe_ns: BTreeMap<String, (usize, usize)> = BTreeMap::new();
        for (name, n) in &asked {
            let ns = if let Some((class, _)) = name.split_once(':') {
                format!("{class} (methods)")
            } else {
                namespace(name).to_string()
            };
            let e = fullprobe_ns.entry(ns).or_default();
            e.0 += n;
            e.1 += missed.get(name).copied().unwrap_or(0);
        }
        // The method probe.
        let methodprobe_seed = !client.join("forever-camelot-methodprobe.lua").exists();
        let mp = ratchet("METHODPROBE_MATCHED")?;
        let (m, t, missed) = misses(root, METHODPROBE_MISSES)?;
        let sum: usize = missed.values().sum();
        if m != mp || t - sum != m {
            return Err(stale(
                &format!("{m} matched of {t} with {sum} missed; the test's ratchet {mp}"),
                METHODPROBE_MISSES,
            ));
        }
        let methodprobe = Measure {
            matched: m,
            total: t,
        };
        // The answers battery, its checks and the maps.
        let answers = Measure {
            matched: ratchet("ANSWERS_MATCHED")?,
            total: lua_strings(&client.join("forever-camelot-answers.lua"))?.len(),
        };
        let checks = lua_strings(&client.join("forever-camelot-checks.lua"))?.len();
        let maps = Measure {
            matched: ratchet("MAPS_MATCHED")?,
            total: lua_strings(&client.join("forever-camelot-maps.lua"))?.len(),
        };
        // The scenario replays: each test's ratchet of the recording's
        // lines as the replay compares them.
        let scenario_dir = client.join("scenarios");
        let mut scenarios = Vec::new();
        let mut played = BTreeSet::new();
        for c in Regex::new(r#"plays_as_the_client_did\("(\w+)", (\w+)\)"#)?.captures_iter(&tests) {
            let name = c[1].to_string();
            let src = fs::read(scenario_dir.join(format!("{name}.lua")))
                .with_context(|| format!("the {name} recording"))?;
            let log = wowlua_test::scenario::recording(&src).map_err(anyhow::Error::msg)?;
            scenarios.push(Scenario {
                matched: ratchet(&c[2])?,
                total: wowlua_test::scenario::lines(&log).len(),
                name: name.clone(),
            });
            played.insert(name);
        }
        scenarios.sort_by(|a, b| a.name.cmp(&b.name));
        let mut unplayed = Vec::new();
        for entry in fs::read_dir(&scenario_dir)? {
            let path = entry?.path();
            if path.extension().is_some_and(|e| e == "lua")
                && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
                && !played.contains(stem)
            {
                unplayed.push(stem.to_string());
            }
        }
        unplayed.sort();
        // The damage meter's events in the fights it replays.
        let fights = Regex::new(
            r#"fn the_engine_tells_the_damage_meter_as_the_client_did\(\) \{\s*let mut matched = 0;\s*for name in \[([^\]]*)\]"#,
        )?
        .captures(&tests)
        .context("the damage meter test's fights")?[1]
            .to_string();
        let mut meter_total = 0;
        for name in Regex::new(r#""(\w+)""#)?.captures_iter(&fights) {
            let src = fs::read(scenario_dir.join(format!("{}.lua", &name[1])))?;
            let log = wowlua_test::scenario::recording(&src).map_err(anyhow::Error::msg)?;
            meter_total += log.iter().filter(|l| l.contains(" DAMAGE_METER_")).count();
        }
        Ok(Verification {
            fullprobe: Measure { matched, total },
            fullprobe_ns,
            methodprobe,
            methodprobe_seed,
            answers,
            checks,
            maps,
            damage_meter: Measure {
                matched: ratchet("DAMAGE_METER_MATCHED")?,
                total: meter_total,
            },
            scenarios,
            unplayed,
        })
    }

    fn write(&self, out: &mut String) {
        out.push_str("## Verification against the client\n\n");
        out.push_str(
            "The engine runs StdTest's probes with the recorded character's world and \
             compares its answers with the client's (`crates/wowlua-cli/tests/engine_probe.rs`). \
             Each comparison has a ratchet, the matched count it may not fall below; the \
             numbers here are those ratchets. The comparisons load Blizzard's UI code \
             (`cargo xtask types fetch`), so they run locally and CI skips them.\n\n",
        );
        out.push_str(
            "| Comparison | Matched | Of | Ratio |\n|------------|--------:|---:|------:|\n",
        );
        let row = |out: &mut String, label: &str, m: &Measure| {
            writeln!(
                out,
                "| {label} | {} | {} | {} |",
                thousands(m.matched),
                thousands(m.total),
                percent(m.matched, m.total)
            )
            .unwrap();
        };
        row(
            out,
            "Full probe (`/stdtest engine fullprobe`: every C function with many arguments)",
            &self.fullprobe,
        );
        row(
            out,
            "Answers battery (`/stdtest engine answers`: the calls Blizzard's UI makes)",
            &self.answers,
        );
        row(
            out,
            if self.methodprobe_seed {
                "Method probe (a fresh widget's recorded getters, until `/stdtest engine methodprobe` is ingested)"
            } else {
                "Method probe (`/stdtest engine methodprobe`: every widget method)"
            },
            &self.methodprobe,
        );
        row(
            out,
            "Maps (`/stdtest engine maps`: each map's data)",
            &self.maps,
        );
        row(
            out,
            "Damage meter (its events in the recorded fights)",
            &self.damage_meter,
        );
        out.push('\n');
        writeln!(
            out,
            "Besides these, the probe battery (`/stdtest engine`), the input, mouse and key \
             replays and the answers battery's {} checks (but those known to vary between \
             the client's sessions) must match exactly, and the \
             taint experiments (`/stdtest taint`) are reproduced in full \
             (`crates/wowlua-engine/tests/taint.rs`).\n",
            thousands(self.checks)
        )
        .unwrap();
        out.push_str("### Scenario replays\n\n");
        out.push_str(
            "Each recorded scenario (`/stdtest engine scenario`) played in the engine from \
             the character's world as the recording began; its lines are the events and \
             answers StdTest's recorder logged, without the world's noise.\n\n",
        );
        out.push_str("| Scenario | Matched | Of | Ratio |\n|----------|--------:|---:|------:|\n");
        let (mut m, mut t) = (0, 0);
        for s in &self.scenarios {
            writeln!(
                out,
                "| {} | {} | {} | {} |",
                s.name,
                thousands(s.matched),
                thousands(s.total),
                percent(s.matched, s.total)
            )
            .unwrap();
            m += s.matched;
            t += s.total;
        }
        writeln!(
            out,
            "| **All** | {} | {} | {} |\n",
            thousands(m),
            thousands(t),
            percent(m, t)
        )
        .unwrap();
        if !self.unplayed.is_empty() {
            let list: Vec<String> = self.unplayed.iter().map(|n| format!("`{n}`")).collect();
            writeln!(out, "Recorded without a replay yet: {}.\n", list.join(", ")).unwrap();
        }
        out.push_str("### The full probe by namespace\n\n");
        out.push_str(
            "The full probe's answers by the namespace of the function asked (a setting's \
             read-back counts for its setter), from the test's misses \
             (`crates/wowlua-cli/tests/fullprobe-misses.txt`):\n\n",
        );
        out.push_str("| Namespace | Answers | Matched | Ratio |\n|-----------|--------:|--------:|------:|\n");
        for (ns, (asked, missed)) in &self.fullprobe_ns {
            let matched = asked - missed;
            writeln!(
                out,
                "| `{ns}` | {} | {} | {} |",
                thousands(*asked),
                thousands(matched),
                percent(matched, *asked)
            )
            .unwrap();
        }
        out.push('\n');
    }
}

// ---------------------------------------------------- unverified rules

/// A comment that marks a rule unverified.
struct Rule {
    /// The module, by its path below `src` (`auras`, `ui/build`).
    module: String,
    file: String,
    summary: String,
}

/// The comment's first sentence, at most 120 characters.
fn first_sentence(text: &str) -> String {
    let mut end = text.len();
    let bytes = text.as_bytes();
    let mut in_code = false;
    for (i, &b) in bytes.iter().enumerate() {
        if b == b'`' {
            in_code = !in_code;
        }
        if !in_code && b == b'.' && bytes.get(i + 1).is_none_or(|n| *n == b' ') {
            // Not an abbreviation (`e.g.`, `i.e.`) nor a number.
            let before = &text[..i];
            if before.ends_with("e.g") || before.ends_with("i.e") || before.ends_with("etc") {
                continue;
            }
            end = i + 1;
            break;
        }
    }
    let sentence = text[..end].trim();
    if sentence.chars().count() > 120 {
        let cut: String = sentence.chars().take(117).collect();
        format!("{}...", cut.trim_end())
    } else {
        sentence.to_string()
    }
}

fn unverified_rules(root: &Path) -> Result<Vec<Rule>> {
    let src = root.join(ENGINE_SRC);
    let mut files: Vec<std::path::PathBuf> = walkdir::WalkDir::new(&src)
        .into_iter()
        .filter_map(|e| e.ok())
        .map(|e| e.into_path())
        .filter(|p| p.extension().is_some_and(|e| e == "rs"))
        .collect();
    files.sort();
    let mut rules = Vec::new();
    for path in files {
        let rel = path
            .strip_prefix(&src)?
            .to_string_lossy()
            .replace('\\', "/");
        let module = rel
            .trim_end_matches(".rs")
            .trim_end_matches("/mod")
            .to_string();
        let file = format!("{ENGINE_SRC}/{rel}");
        let text = fs::read_to_string(&path)?;
        // Comment paragraphs: consecutive comment lines up to an empty
        // one; a trailing comment is one of its own.
        let mut block: Vec<String> = Vec::new();
        let mut flush = |block: &mut Vec<String>| {
            if block
                .iter()
                .any(|t| t.to_ascii_lowercase().contains("unverified"))
            {
                let joined: Vec<&str> = block.iter().map(String::as_str).collect();
                rules.push(Rule {
                    module: module.clone(),
                    file: file.clone(),
                    summary: first_sentence(&joined.join(" ")),
                });
            }
            block.clear();
        };
        for line in text.lines() {
            let trimmed = line.trim_start();
            if let Some(rest) = trimmed.strip_prefix("//") {
                let rest = rest.trim_start_matches(['/', '!']).trim();
                if rest.is_empty() {
                    flush(&mut block);
                } else {
                    block.push(rest.to_string());
                }
                continue;
            }
            flush(&mut block);
            if let Some((_, comment)) = line.split_once(" // ") {
                block.push(comment.trim().to_string());
                flush(&mut block);
            }
        }
        flush(&mut block);
    }
    Ok(rules)
}

fn write_unverified(out: &mut String, rules: &[Rule]) {
    out.push_str("## Unverified rules\n\n");
    writeln!(
        out,
        "The engine's code marks {} rules unverified: each rests on Blizzard's \
         documentation or UI code, warcraft.wiki.gg, elune or the function's name, not \
         on a probe of the client. An in-game probe confirms or corrects each \
         ([probes](../tests/ingame/PROBES.md)). Each line is the marking comment's first \
         sentence, in the file's order; the file is cited without a line number so the \
         page changes only when a rule is added, removed or reworded.\n",
        thousands(rules.len())
    )
    .unwrap();
    let mut by_module: BTreeMap<&str, Vec<&Rule>> = BTreeMap::new();
    for r in rules {
        by_module.entry(&r.module).or_default().push(r);
    }
    for (module, list) in by_module {
        writeln!(out, "### {module} ({})\n", list.len()).unwrap();
        for r in list {
            writeln!(
                out,
                "- [{}](../{}): {}",
                r.file.trim_start_matches(&format!("{ENGINE_SRC}/")),
                r.file,
                r.summary
            )
            .unwrap();
        }
        out.push('\n');
    }
}

// --------------------------------------------- probes and regressions

fn probes(out: &mut String, root: &Path) -> Result<()> {
    let text = fs::read_to_string(root.join(PROBES)).with_context(|| PROBES.to_string())?;
    out.push_str("## In-game probes that would close gaps\n\n");
    out.push_str(
        "The probes to run in the client next, what each answers and how to run it, are \
         in [tests/ingame/PROBES.md](../tests/ingame/PROBES.md):\n\n",
    );
    for heading in text.lines().filter_map(|l| l.strip_prefix("## ")) {
        writeln!(out, "- {heading}")?;
    }
    out.push('\n');
    Ok(())
}

fn regressions(out: &mut String, root: &Path) -> Result<()> {
    let text =
        fs::read_to_string(root.join(REGRESSIONS)).with_context(|| REGRESSIONS.to_string())?;
    out.push_str("## In-game regressions\n\n");
    out.push_str(
        "The bugs found in the game that must fail in the emulator as they failed there \
         (spec §17.8), and the tests that hold them:\n\n",
    );
    out.push_str("| Bug found in game | Test |\n|-------------------|------|\n");
    for line in text
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
    {
        let fields: Vec<&str> = line.split('\t').collect();
        let [bug, tests @ ..] = fields.as_slice() else {
            continue;
        };
        let mut cells = Vec::new();
        for test in tests.iter().filter(|t| !t.is_empty()) {
            let Some((file, name)) = test.split_once("::") else {
                cells.push((*test).to_string());
                continue;
            };
            let src = fs::read_to_string(root.join(file)).with_context(|| file.to_string())?;
            if !src.contains(&format!("fn {name}(")) {
                bail!("{REGRESSIONS}: no test `{name}` in {file}");
            }
            cells.push(format!("`{name}` ([{file}](../{file}))"));
        }
        if cells.is_empty() {
            cells.push("**none yet**".to_string());
        }
        writeln!(out, "| {bug} | {} |", cells.join("; "))?;
    }
    out.push('\n');
    Ok(())
}
