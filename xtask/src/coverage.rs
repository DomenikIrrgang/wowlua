//! `cargo xtask coverage-report`: the emulator's coverage report
//! (`docs/emulator-coverage.md`, spec emulator §17.8), generated from the
//! engine's registration tables, the recorded fixtures, the replay tests'
//! ratchets and the engine's "unverified" comments, with the hand-written
//! gaps and regressions (`crates/wowlua-engine/data/coverage-*`). It reads
//! checked-in files only (no `target/types-src`), so every machine writes
//! the same report and `cargo xtask check` can tell a stale one.

use anyhow::{Context, Result, bail};
use regex::Regex;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::fs;
use std::path::Path;
use wowlua_engine::coverage::{Entry, Group, Source};
use wowlua_vm::{Value, Vm};

pub const REPORT: &str = "docs/emulator-coverage.md";
const PROBE_TESTS: &str = "crates/wowlua-cli/tests/engine_probe.rs";
const CLIENT: &str = "crates/wowlua-engine/tests/client";
const ENGINE_SRC: &str = "crates/wowlua-engine/src";
const GAPS: &str = "crates/wowlua-engine/data/coverage-gaps.md";
const REGRESSIONS: &str = "crates/wowlua-engine/data/coverage-regressions.txt";
const PROBES: &str = "tests/ingame/PROBES.md";
/// The client's every function, C or Lua (`/stdtest inventory`).
const INVENTORY: &str = "crates/wowlua-vm/tests/client/forever-camelot-functions.tsv";
const FULLPROBE_MISSES: &str = "crates/wowlua-cli/tests/fullprobe-misses.txt";
const METHODPROBE_MISSES: &str = "crates/wowlua-cli/tests/methodprobe-misses.txt";

/// The flavor the recordings come from.
const FOCUS: &str = "camelot";

pub fn generate(root: &Path) -> Result<String> {
    let mut out = String::new();
    let functions = wowlua_engine::coverage::functions(FOCUS).map_err(anyhow::Error::msg)?;
    let methods = wowlua_engine::coverage::methods(FOCUS).map_err(anyhow::Error::msg)?;
    let verification = Verification::read(root)?;
    let unverified = unverified_rules(root)?;
    out.push_str(
        "<!-- Generated by `cargo xtask coverage-report`: do not edit. The gaps come from \
         crates/wowlua-engine/data/coverage-gaps.md, the regressions from \
         crates/wowlua-engine/data/coverage-regressions.txt. -->\n\n",
    );
    out.push_str("# Emulator coverage\n\n");
    out.push_str(
        "How much of the WoW client `wowlua test` emulates (spec \
         [§17.8](../spec/toolchain/emulator.md#178-verification)): which API functions \
         have behaviour, which only have the stand-in generated from Blizzard's \
         documentation, how the engine's answers compare with the real client's, and \
         what is still missing. `cargo xtask coverage-report` writes this page from the \
         engine's own tables and the recorded fixtures; `cargo xtask check` fails when it \
         is out of date.\n\n",
    );
    summary(
        &mut out,
        root,
        &functions,
        &methods,
        &verification,
        &unverified,
    )?;
    let inventory_path = root.join(INVENTORY);
    let inventory = fs::read_to_string(&inventory_path).with_context(|| INVENTORY.to_string())?;
    behaviour(&mut out, &functions, &methods, &inventory);
    verification.write(&mut out);
    write_unverified(&mut out, &unverified);
    let gaps = fs::read_to_string(root.join(GAPS)).with_context(|| GAPS.to_string())?;
    out.push_str("## Known gaps\n\n");
    out.push_str(gaps.trim_end());
    out.push_str("\n\n");
    probes(&mut out, root)?;
    regressions(&mut out, root)?;
    Ok(wrap(&out))
}

/// The page's prose and list items wrapped at 80 columns, as the
/// documentation is written; tables, headings and comments as they are.
fn wrap(md: &str) -> String {
    const WIDTH: usize = 80;
    // A word that would start a list, a heading, a table or a quote.
    let significant = |w: &str| {
        matches!(w, "-" | "+" | "*" | ">" | "|")
            || w.starts_with('#')
            || (w.len() > 1
                && w.ends_with('.')
                && w[..w.len() - 1].bytes().all(|b| b.is_ascii_digit()))
    };
    let mut out = String::new();
    for line in md.split_inclusive('\n') {
        let body = line.trim_end_matches('\n');
        if body.chars().count() <= WIDTH
            || body.starts_with('|')
            || body.starts_with('#')
            || body.starts_with("<!--")
            // A rule's line: one line each.
            || body.starts_with("- [")
        {
            out.push_str(line);
            continue;
        }
        // A list item's continuation under its text, a continued line's
        // under its own start.
        let lead = body.len() - body.trim_start().len();
        let item = if body.trim_start().starts_with("- ") {
            2
        } else {
            0
        };
        let indent = " ".repeat(lead + item);
        let mut current = " ".repeat(lead);
        for word in body.trim_start().split(' ') {
            let fits = current.chars().count() + 1 + word.chars().count() <= WIDTH;
            if !current.trim().is_empty() && current.trim() != "-" && !fits && !significant(word) {
                out.push_str(current.trim_end());
                out.push('\n');
                current = indent.clone();
            } else if !current.is_empty() && !current.ends_with(' ') {
                current.push(' ');
            }
            current.push_str(word);
        }
        out.push_str(current.trim_end());
        out.push('\n');
    }
    out
}

